"""recipes.route — declarative case routing over a group's entry trigger.

A common multi-agent shape is "one artifact carries the branch key, and only
one downstream group should run for each value". Hand-written
`Consume(..., condition=lambda ...)` gets this right per group, but the
exclusivity lives only in the conditions; nothing checks that two groups cannot
both produce the terminal artifact.

`Route` keeps the runtime flat (no nested groups): it wraps each case
`Agent` and narrows only matches of the route's `on` event by
`key(value) == case`. Downstream steps that react to later events
(`SearchDone`, `ToolAnswer`, …) are untouched. Generated groups carry a
`route_case` marker, so `validate_contracts` can treat the cases as exclusive
and still warn about producers outside the route.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from pydantic import BaseModel

from ..agent import Agent
from ..context import Context
from ..events import Event


@dataclass(frozen=True)
class RouteCase:
    """Machine-readable marker on a group generated by `Route`."""

    route: str
    case: str
    default: bool = False


class _RoutedGroup(Agent):
    def __init__(
        self,
        inner: Agent,
        route_case: RouteCase,
        *,
        label: str,
        on: type[BaseModel],
        key: Callable[[Any], Any],
        cases: Mapping[str, Any],
    ) -> None:
        self.inner = inner
        self.route_case = route_case
        self._route_on = on
        self._route_key = key
        self._route_cases = cases
        super().__init__(
            name=label,
            steps=inner.steps,
            triggers=list(inner.triggers),
            priority=inner.priority,
            retry=inner.retry,
            timeout=inner.timeout,
            wakes=inner.wakes,
            fallback=inner.fallback_step,
            fallback_on=inner.fallback_on,
            fallback_skip=inner.fallback_skip,
        )
        # `Agent.__init__` cannot overwrite inherited state here, so preserve the
        # inner group's contract explicitly. Besides validation, this keeps
        # `collect_inputs()` (reads/provenance) aligned with the inner group.
        self.consumes = list(inner.consumes) if inner.consumes is not None else None
        self.capabilities = inner.capabilities
        self.concurrency_limit = inner.concurrency_limit
        self._validate_contracts()

    def _route_allows(self, event: Event, context: Context | None) -> bool:
        if event.artifact_type is not self._route_on:
            return True
        if context is None:
            return False
        artifact = context.get(event.artifact_id)
        if artifact is None:
            return False
        value = self._route_key(artifact.data)
        if self.route_case.default:
            return bool(value not in self._route_cases or value == self.route_case.case)
        return bool(value == self.route_case.case)

    def matching_triggers(
        self, event: Event, context: Context | None = None
    ) -> list[Any]:
        # `Runtime` calls this directly (not `matches`), so the route gate
        # belongs here; `matches` inherits the same check through it.
        if not self._route_allows(event, context):
            return []
        return super().matching_triggers(event, context)

    async def run(self, event: Event, context: Context) -> Any:
        # The inner group owns its steps/config; the wrapper only gates wakes.
        return await self.inner.run(event, context)


def _case_agents(
    value: Agent | Sequence[Agent],
) -> tuple[Agent, ...]:
    if isinstance(value, Agent):
        return tuple(value.agents())
    return tuple(group for item in value for group in _case_agents(item))


class Route:
    """Builds one routed copy of each case group.

        route = Route(
            on=ResearchTurn,
            key=lambda turn: turn.domain,
            cases={"meta": kb_react_group, "rag": rag_group},
            default="rag",
        )
        Runtime(ctx, agents=[*route.agents(), planner])

    `cases` values are an `Agent` or a sequence of them. An
    agent can be routed when it reacts to `on` (agent `consumes` or one of its
    step `reads`); other triggers keep working unchanged. `default`
    must name a case and covers values not present in `cases`; without it, an
    unknown value wakes no case.

    `agents()` returns one routed **copy** per case (`_RoutedGroup`), not the
    inner agent. The copy preserves steps, triggers, retry, priority and
    fallback policy, and exposes `.inner` plus `.route_case` for inspection.
    Cases may also contain an agent that does not react to `on` at all; its
    own triggers keep working, while the route marker still tells
    `validate_contracts` that the cases' outputs are mutually exclusive.
    Pass the `Route` itself to `Runtime(agents=[route, ...])`,
    `Pipeline(agents=[route, ...])` or `validate_contracts(agents=[route])` to
    expand it; `.agents()` is the manual spelling.
    """

    def __init__(
        self,
        *,
        on: type[BaseModel],
        key: Callable[[Any], Any],
        cases: Mapping[str, Agent | Sequence[Agent]],
        default: str | None = None,
        name: str | None = None,
    ) -> None:
        if not cases:
            raise ValueError("Route needs at least one case")
        if default is not None and default not in cases:
            raise ValueError("Route.default must name one of cases")
        self.on = on
        self.key = key
        self.cases = dict(cases)
        self.default = default
        self.name = name or on.__name__.lower()

    def agents(self) -> list[Agent]:
        """The routed case agents, ready for `Runtime(agents=...)`."""
        generated: list[Agent] = []
        for case, value in self.cases.items():
            agents = _case_agents(value)
            if not agents:
                raise ValueError(f"Route case {case!r} has no agents")
            for index, group in enumerate(agents):
                suffix = f":{index}" if len(agents) > 1 else ""
                marker = RouteCase(
                    route=self.name,
                    case=case,
                    default=case == self.default,
                )
                generated.append(
                    _RoutedGroup(
                        group,
                        marker,
                        label=f"{self.name}:{case}{suffix}",
                        on=self.on,
                        key=self.key,
                        cases=self.cases,
                    )
                )
        return generated


__all__ = ["Route", "RouteCase"]
