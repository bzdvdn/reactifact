"""recipes.route — declarative case routing over a group's entry trigger.

A common multi-agent shape is "one artifact carries the branch key, and only
one downstream group should run for each value". Hand-written
`Consume(..., condition=lambda ...)` gets this right per group, but the
exclusivity lives only in the conditions; nothing checks that two groups cannot
both produce the terminal artifact.

`Route` keeps the runtime flat (no nested groups): it wraps each case
`StepGroup` and narrows only matches of the route's `on` event by
`key(value) == case`. Downstream steps that react to later events
(`SearchDone`, `ToolAnswer`, …) are untouched. Generated groups carry a
`route_case` marker, so `validate_contracts` can treat the cases as exclusive
and still warn about producers outside the route.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from pydantic import BaseModel

from ..context import Context
from ..events import Event
from ..step import StepGroup


@dataclass(frozen=True)
class RouteCase:
    """Machine-readable marker on a group generated by `Route`."""

    route: str
    case: str
    default: bool = False


class _RoutedGroup(StepGroup):
    def __init__(
        self,
        inner: StepGroup,
        route_case: RouteCase,
        *,
        label: str,
        on: type[BaseModel],
        key: Callable[[Any], Any],
        cases: Mapping[str, Any],
    ) -> None:
        self.inner = inner
        self.route_case = route_case
        self._route_on = on
        self._route_key = key
        self._route_cases = cases
        super().__init__(
            name=label,
            steps=inner.steps,
            triggers=list(inner.triggers),
            priority=inner.priority,
            retry=inner.retry,
            timeout=inner.timeout,
            wakes=inner.wakes,
        )

    def _route_allows(self, event: Event, context: Context | None) -> bool:
        if event.artifact_type is not self._route_on:
            return True
        if context is None:
            return False
        artifact = context.get(event.artifact_id)
        if artifact is None:
            return False
        value = self._route_key(artifact.data)
        if self.route_case.default:
            return bool(value not in self._route_cases or value == self.route_case.case)
        return bool(value == self.route_case.case)

    def matching_triggers(
        self, event: Event, context: Context | None = None
    ) -> list[Any]:
        # `Runtime` calls this directly (not `matches`), so the route gate
        # belongs here; `matches` inherits the same check through it.
        if not self._route_allows(event, context):
            return []
        return super().matching_triggers(event, context)

    async def run(self, event: Event, context: Context) -> Any:
        # The inner group owns its steps/config; the wrapper only gates wakes.
        return await self.inner.run(event, context)


class Route:
    """Builds one routed copy of each case group.

        route = Route(
            on=ResearchTurn,
            key=lambda turn: turn.domain,
            cases={"meta": kb_react_group, "rag": rag_group},
            default="rag",
        )
        Runtime(ctx, groups=[*route.groups(), planner])

    `cases` values are a `StepGroup` or a sequence of them. A group can be
    routed when it reacts to `on` (group-level `consumes` or one of its step
    consumes); other triggers keep working unchanged. `default` must name a
    case and covers values not present in `cases`; without it, an unknown value
    wakes no case.
    """

    def __init__(
        self,
        *,
        on: type[BaseModel],
        key: Callable[[Any], Any],
        cases: Mapping[str, StepGroup | Sequence[StepGroup]],
        default: str | None = None,
        name: str | None = None,
    ) -> None:
        if not cases:
            raise ValueError("Route needs at least one case")
        if default is not None and default not in cases:
            raise ValueError("Route.default must name one of cases")
        self.on = on
        self.key = key
        self.cases = dict(cases)
        self.default = default
        self.name = name or on.__name__.lower()

    def groups(self) -> list[StepGroup]:
        """The routed case groups, ready for `Runtime(groups=...)`."""
        generated: list[StepGroup] = []
        for case, value in self.cases.items():
            groups = (value,) if isinstance(value, StepGroup) else tuple(value)
            if not groups:
                raise ValueError(f"Route case {case!r} has no groups")
            for index, group in enumerate(groups):
                suffix = f":{index}" if len(groups) > 1 else ""
                marker = RouteCase(
                    route=self.name,
                    case=case,
                    default=case == self.default,
                )
                generated.append(
                    _RoutedGroup(
                        group,
                        marker,
                        label=f"{self.name}:{case}{suffix}",
                        on=self.on,
                        key=self.key,
                        cases=self.cases,
                    )
                )
        return generated


__all__ = ["Route", "RouteCase"]
